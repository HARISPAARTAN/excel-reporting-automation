"""Notification (spec 6.6): one EmailMessage for dry-run and smtp, written as .eml; smtp also sends it.

MIME boundaries come from the report hash and the Date from the run timestamp, so the .eml is reproducible.
SMTP settings come only from BUILD_REPORT_SMTP_* environment variables.
"""

from __future__ import annotations

import hashlib
import html
import smtplib
import ssl
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from email.headerregistry import Address
from email.message import EmailMessage
from email.policy import SMTP
from email.utils import format_datetime
from typing import TYPE_CHECKING, Literal, cast

from buildreport import __version__
from buildreport.config import Config
from buildreport.findings import counts
from buildreport.isoweek import format_range
from buildreport.metrics import change, count_text, format_change, format_value, threshold_text

if TYPE_CHECKING:
    from buildreport.workbook import BuildContext

TIMEOUT = 30
DEFAULT_PORT = 587
LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1"})
Security = Literal["starttls", "ssl", "none"]


class NotifyError(Exception):
    """Sending failed; the report and the .eml are kept (exit code 4)."""


class SmtpConfigError(ValueError):
    """BUILD_REPORT_SMTP_* is incomplete or invalid (exit code 2)."""


@dataclass(frozen=True)
class SmtpSettings:
    host: str
    port: int
    user: str | None
    password: str | None = field(repr=False)
    security: Security


def smtp_settings(env: Mapping[str, str]) -> SmtpSettings:
    host = env.get("BUILD_REPORT_SMTP_HOST", "").strip()
    if not host:
        raise SmtpConfigError("--notify smtp needs the environment variable BUILD_REPORT_SMTP_HOST")
    raw_port = env.get("BUILD_REPORT_SMTP_PORT", "").strip() or str(DEFAULT_PORT)
    if not raw_port.isdigit() or not 0 < int(raw_port) < 65536:
        raise SmtpConfigError(f"BUILD_REPORT_SMTP_PORT must be a port number, got {raw_port!r}")
    user = env.get("BUILD_REPORT_SMTP_USER", "").strip() or None
    password = env.get("BUILD_REPORT_SMTP_PASSWORD", "") or None
    if (user is None) != (password is None):
        raise SmtpConfigError("BUILD_REPORT_SMTP_USER and BUILD_REPORT_SMTP_PASSWORD must be set together")
    security = env.get("BUILD_REPORT_SMTP_SECURITY", "").strip().lower() or "starttls"
    if security not in ("starttls", "ssl", "none"):
        raise SmtpConfigError(f"BUILD_REPORT_SMTP_SECURITY must be starttls, ssl or none, got {security!r}")
    if security == "none" and host not in LOCAL_HOSTS:
        raise SmtpConfigError("BUILD_REPORT_SMTP_SECURITY=none is allowed only for localhost and 127.0.0.1")
    return SmtpSettings(host, int(raw_port), user, password, cast(Security, security))


def recipients(cfg: Config) -> list[str]:
    notify = cfg.model.notify
    return [*notify.to, *notify.cc]


def _revenue(ctx: BuildContext) -> tuple[str, str]:
    result, spec = ctx.result, ctx.cfg.metric("revenue")
    current = result.chain_value(result.period, "revenue")
    before = result.chain_value(result.previous, "revenue")
    return format_value(current, spec.format), format_change(
        change(current, before, spec.change), spec.change
    )


def subject(ctx: BuildContext) -> str:
    value, delta = _revenue(ctx)
    total = len(ctx.resolution.findings)
    prefix = ctx.cfg.model.notify.subject_prefix
    return f"{prefix} {ctx.result.period}: revenue {value} ({delta} WoW), {count_text(total, 'finding')}"


def _facts(ctx: BuildContext) -> dict[str, str]:
    summary = ctx.summary
    tally = counts(ctx.resolution.findings)
    top = summary.top
    if top is None:
        top_text = "Top-ranked branch: none (no branch reported)."
    else:
        top_text = f"Top-ranked branch: {top.name} ({format_value(top.revenue, ctx.cfg.metric('revenue').format)} revenue)."
    return {
        "title": f"{ctx.cfg.model.notify.subject_prefix} {summary.period}",
        "dates": format_range(summary.period),
        "top": top_text,
        "reporting": (
            f"Branches reporting: {summary.reporting_now} this week, "
            f"{summary.reporting_previous} last week, {summary.expected} expected."
        ),
        "findings": (
            f"Findings: {count_text(tally['error'], 'error')}, {count_text(tally['warning'], 'warning')}; "
            "details on the sheet Run info."
        ),
        "generated": f"Generated by build-report {__version__}.",
    }


def _rows(ctx: BuildContext) -> list[tuple[str, str, str, str]]:
    return [
        (
            kpi.label,
            format_value(kpi.value, kpi.format),
            format_value(kpi.previous, kpi.format),
            format_change(kpi.change, kpi.change_type),
        )
        for kpi in ctx.summary.kpis
    ]


def text_body(ctx: BuildContext, xlsx_name: str) -> str:
    facts = _facts(ctx)
    lines = [
        facts["title"],
        facts["dates"],
        "",
        f"The weekly report is attached as {xlsx_name}.",
        "",
        f"{'Key figures':<26}{'This week':>13}{'Last week':>13}{'Change':>11}",
    ]
    lines += [
        f"{label:<26}{value:>13}{previous:>13}{delta:>11}" for label, value, previous, delta in _rows(ctx)
    ]
    lines += ["", "Thresholds:"]
    lines += [f"- {threshold_text(hit)}" for hit in ctx.summary.above_threshold] or ["- none configured"]
    lines += ["", facts["top"], facts["reporting"], facts["findings"], "", facts["generated"], ""]
    return "\n".join(lines)


CELL = "padding:4px 10px;border-bottom:1px solid #d8dde3;"


def html_body(ctx: BuildContext, xlsx_name: str) -> str:
    facts = _facts(ctx)
    escape = html.escape
    rows = "".join(
        f'<tr><td style="{CELL}">{escape(label)}</td><td style="{CELL}text-align:right">{escape(value)}</td>'
        f'<td style="{CELL}text-align:right">{escape(previous)}</td><td style="{CELL}text-align:right">{escape(delta)}</td></tr>'
        for label, value, previous, delta in _rows(ctx)
    )
    hits = (
        "".join(f"<li>{escape(threshold_text(hit))}</li>" for hit in ctx.summary.above_threshold)
        or "<li>none configured</li>"
    )
    head = "".join(
        f'<th style="{CELL}text-align:{align};background:#1f2a36;color:#ffffff">{name}</th>'
        for name, align in (
            ("Key figures", "left"),
            ("This week", "right"),
            ("Last week", "right"),
            ("Change", "right"),
        )
    )
    return (
        "<!doctype html>\n"
        '<html lang="en"><body style="font-family:Calibri,Arial,sans-serif;font-size:14px;color:#14181d">'
        f'<h1 style="font-size:20px;margin:0 0 4px">{escape(facts["title"])}</h1>'
        f'<p style="margin:0 0 12px;color:#5b6472">{escape(facts["dates"])}</p>'
        f"<p>The weekly report is attached as <strong>{escape(xlsx_name)}</strong>.</p>"
        f'<table style="border-collapse:collapse"><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table>'
        f'<p style="margin:12px 0 4px">Thresholds:</p><ul style="margin:0">{hits}</ul>'
        f"<p>{escape(facts['top'])}<br>{escape(facts['reporting'])}<br>{escape(facts['findings'])}</p>"
        f'<p style="color:#5b6472">{escape(facts["generated"])}</p>'
        "</body></html>\n"
    )


def _domain(address: str) -> str:
    return address.rsplit("@", 1)[1]


def build_message(
    ctx: BuildContext, xlsx_name: str, xlsx_bytes: bytes, mode: Literal["dry-run", "smtp"]
) -> EmailMessage:
    notify = ctx.cfg.model.notify
    digest = hashlib.sha256(xlsx_bytes).hexdigest()
    sender = notify.sender
    message = EmailMessage(policy=SMTP)
    message["From"] = Address(display_name=sender.name, addr_spec=sender.address)
    message["To"] = ", ".join(notify.to)
    if notify.cc:
        message["Cc"] = ", ".join(notify.cc)
    message["Subject"] = subject(ctx)
    message["Date"] = format_datetime(ctx.timestamp.value)
    message["Message-ID"] = f"<{ctx.result.period}.{digest[:16]}@{_domain(sender.address)}>"
    message["X-Build-Report-Mode"] = mode
    message.set_content(text_body(ctx, xlsx_name), cte="quoted-printable")
    message.add_alternative(html_body(ctx, xlsx_name), subtype="html", cte="quoted-printable")
    message.add_attachment(
        xlsx_bytes,
        maintype="application",
        subtype="vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        filename=xlsx_name,
    )
    message.set_boundary(f"=_mixed_{digest[:32]}")
    alternative = cast(EmailMessage, message.get_payload(0))
    alternative.set_boundary(f"=_alt_{digest[:32]}")
    return message


def to_bytes(message: EmailMessage) -> bytes:
    return message.as_bytes(policy=SMTP)


def send(message: EmailMessage, settings: SmtpSettings, sender: str, to_addrs: Sequence[str]) -> None:
    """Send with a 30 s timeout; STARTTLS or implicit TLS use ssl.create_default_context()."""
    context = ssl.create_default_context()
    try:
        client: smtplib.SMTP
        if settings.security == "ssl":
            client = smtplib.SMTP_SSL(settings.host, settings.port, timeout=TIMEOUT, context=context)
        else:
            client = smtplib.SMTP(settings.host, settings.port, timeout=TIMEOUT)
        with client:
            if settings.security == "starttls":
                client.starttls(context=context)
            if settings.user is not None and settings.password is not None:
                client.login(settings.user, settings.password)
            client.send_message(message, from_addr=sender, to_addrs=list(to_addrs))
    except UnicodeError as exc:
        raise NotifyError(
            f"sending through {settings.host}:{settings.port} failed: the SMTP credentials must be ASCII"
        ) from exc
    except (smtplib.SMTPException, OSError) as exc:
        raise NotifyError(f"sending through {settings.host}:{settings.port} failed: {exc}") from exc
